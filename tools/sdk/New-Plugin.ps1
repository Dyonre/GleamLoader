<#
New-Plugin.ps1 - scaffold an AbsolverSE (script extender) plugin folder: plugin.c (logging, config, ready/tick/hit/menu skeleton),
build.bat (MSVC Build Tools 2022 x64, header taken from this repo's tools\lannative), plugin.cfg, mod.json.

  powershell -ExecutionPolicy Bypass -File tools\sdk\New-Plugin.ps1 -Name MyPlugin [-Dest <local path>] [-Build]

  -Name   mod folder name = mod id (letters, digits, _ - .; max 95)
  -Dest   parent folder (default <repo>\work\sdk-out). The plugin is created in <Dest>\<Name>. Never inside the game folder.
  -Build  run build.bat afterwards and check that plugin.dll exists
  -Force  overwrite an existing folder's generated files
Never deploys anything: copy plugin.dll + mod.json + plugin.cfg to <game>\Mods\<Name>\ yourself (docs\sdk\README.md section 4).
#>
param([Parameter(Mandatory)][string]$Name, [string]$Dest, [switch]$Build, [switch]$Force)
$ErrorActionPreference = 'Stop'
$repo = (Resolve-Path (Join-Path $PSScriptRoot '..\..')).Path
$hdrDir = Join-Path $repo 'tools\lannative'
if ($Name -notmatch '^[A-Za-z0-9_.\-]{1,95}$') { throw "bad -Name '$Name': letters, digits, _ - . only, max 95" }
if (-not $Dest) { $Dest = Join-Path $repo 'work\sdk-out' }
if (-not (Test-Path -LiteralPath (Join-Path $hdrDir 'AbsolverSE.h'))) { throw "AbsolverSE.h not found in $hdrDir" }
$dir = Join-Path $Dest $Name
if ((Test-Path -LiteralPath (Join-Path $dir 'plugin.c')) -and -not $Force) { throw "$dir\plugin.c exists (use -Force to overwrite)" }
New-Item -ItemType Directory -Force $dir | Out-Null
$cid = ($Name -replace '[^A-Za-z0-9_]', '_')

$pluginC = @'
/* @@NAME@@ - AbsolverSE plugin (API v2). Generated by tools\sdk\New-Plugin.ps1; guide: docs\sdk\README.md, reference: docs\sdk\API-REFERENCE.md.
 * Build: build.bat -> plugin.dll. Install: <game>\Mods\@@NAME@@\{plugin.dll, mod.json, plugin.cfg}, remove the '#' before the name in Mods\plugins.txt
 * after the first start, start again, read Binaries\Win64\LanNative\lannative.log (lines "plugin @@NAME@@: ..."). */
#include <windows.h>
#include <stddef.h>
#include <stdio.h>
#include <stdlib.h>
#include <string.h>
#include "AbsolverSE.h"

static const AbsApi *A;                 /* keep the pointer for the whole game: the struct stays valid */
static int g_verbose;                   /* plugin.cfg: verbose = 1 */
static int g_ticks;

/* Heavy logging by default: every callback logs its first few calls, so a failed run explains itself. */
#define LOG(...) A->log(A, __VA_ARGS__)
#define LOGV(...) do { if (g_verbose) A->log(A, __VA_ARGS__); } while (0)

/* Only call fields newer than the version you built against after this check. */
#define HAS(field) (A->size >= offsetof(AbsApi, field) + sizeof(void *))

static void on_ready(void *user)        /* once, first game tick: GEngine exists, safe to use find_object / load_object / reflection */
{
    (void)user;
    LOG("engine ready (game thread: %d)", A->is_game_thread(A));
}

static void on_tick(float dt, void *user)   /* game thread, every frame: keep it cheap */
{
    (void)user; (void)dt;
    if (++g_ticks == 1 || (g_verbose && g_ticks % 1800 == 0)) LOG("tick %d", g_ticks);
}

static void on_hit(const AbsHitInfo *h, void *user)   /* game thread; one event per resolved impact */
{
    (void)user;
    static int n; if (n++ < 20) LOG("hit: attack %s id %d damage %.1f outcome %d", h->attack, h->attack_id, h->damage, h->outcome);
}

static void menu_cb(void *user)         /* chosen from the F1 menu's Mods page (F2) */
{
    (void)user;
    LOG("menu item chosen");
}

__declspec(dllexport) int AbsPlugin_Load(const AbsApi *api)
{
    if (!api || api->version != ABS_API_VERSION || api->size < sizeof(AbsApi)) return 1;   /* 0 = ok; anything else = plugin stays off (logged) */
    A = api;
    char v[64] = "";
    if (A->config_get(A, "verbose", v, sizeof v)) g_verbose = atoi(v);
    LOG("%s loaded from %s (api %u, size %u, verbose %d)", A->plugin_name, A->plugin_dir, A->version, A->size, g_verbose);

    if (A->on_engine_ready(A, on_ready, NULL)) LOG("on_engine_ready failed");
    if (A->on_tick(A, on_tick, NULL)) LOG("on_tick failed");
    if (HAS(on_hit) && A->on_hit(A, on_hit, NULL)) LOG("on_hit failed");
    if (HAS(add_menu_item)) A->add_menu_item(A, "say hello", menu_cb, NULL);
    return 0;
}

__declspec(dllexport) void AbsPlugin_Unload(void) { if (A) A->log(A, "unload"); }   /* optional; called at game exit */
'@

$buildBat = @'
@echo off
rem Builds plugin.dll with MSVC Build Tools 2022 (x64). Generated by tools\sdk\New-Plugin.ps1.
setlocal
call "C:\Program Files (x86)\Microsoft Visual Studio\2022\BuildTools\VC\Auxiliary\Build\vcvars64.bat" >nul 2>nul || (echo vcvars64.bat not found: install MSVC Build Tools 2022 & exit /b 1)
cd /d "%~dp0"
cl /nologo /O2 /MT /W3 /D_CRT_SECURE_NO_WARNINGS /I "@@HDR@@" /LD plugin.c /Fe:plugin.dll /link /NOLOGO user32.lib kernel32.lib || exit /b 1
echo built %~dp0plugin.dll
'@

$mod = @'
{
  "id": "@@NAME@@",
  "name": "@@NAME@@",
  "version": "0.1.0",
  "api": 2,
  "author": "you",
  "description": "What this plugin does.",
  "affects_gameplay": true
}
'@

$cfg = "# plugin.cfg: key = value (read with api->config_get)`r`nverbose = 1`r`n"
function W($file, $text) { [IO.File]::WriteAllText((Join-Path $dir $file), (($text -replace '@@NAME@@', $Name -replace '@@CID@@', $cid -replace '@@HDR@@', $hdrDir) -replace "`r?`n", "`r`n"), (New-Object Text.UTF8Encoding $false)) }
W 'plugin.c' $pluginC; W 'build.bat' $buildBat; W 'mod.json' $mod; W 'plugin.cfg' $cfg
Write-Host "created $dir : plugin.c build.bat mod.json plugin.cfg (header: $hdrDir\AbsolverSE.h)"
if ($Build) {
    & cmd.exe /c "`"$dir\build.bat`""
    if ($LASTEXITCODE -ne 0 -or -not (Test-Path -LiteralPath (Join-Path $dir 'plugin.dll'))) { throw "build failed (exit $LASTEXITCODE)" }
    Write-Host "OK: $dir\plugin.dll"
}
